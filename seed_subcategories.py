def main() -> int:
    app = create_app()
    with app.app_context():
        cats = {c.slug: c for c in Category.query.all()}
        added = 0
        skipped = 0
        missing_slugs: list[str] = []

        for slug, names in SUBS.items():
            cat = cats.get(slug)
            if not cat:
                missing_slugs.append(slug)
                continue

            existing_rows = Subcategory.query.filter_by(category_id=cat.id).all()
            existing_slugs = {(s.slug or "").lower() for s in existing_rows}
            existing_names = {(s.name or "").strip().lower() for s in existing_rows}

            for name in names:
                name = name.strip()
                if not name:
                    continue
                if name.lower() in existing_names:
                    skipped += 1
                    continue

                sslug = slugify(name)
                base = sslug
                n = 2
                while sslug in existing_slugs:
                    sslug = f"{base}{n}"[:60]
                    n += 1
                    if n > 30:
                        break

                db.session.add(
                    Subcategory(
                        category_id=cat.id,
                        name=name,
                        slug=sslug,
                        sort_order=0,
                    )
                )
                existing_slugs.add(sslug)
                existing_names.add(name.lower())
                added += 1

        db.session.commit()
        total = Subcategory.query.count()
        print(f"added={added} skipped={skipped} total_subs_now={total}")
        if missing_slugs:
            print("missing category slugs:", ", ".join(missing_slugs))

        for slug in ("aids", "work", "dark", "sex", "cancer", "pedo", "rape"):
            c = cats.get(slug)
            if not c:
                continue
            n = Subcategory.query.filter_by(category_id=c.id).count()
            print(f"  {c.name}: {n} subcategories")

        empty = [
            c.name
            for c in Category.query.order_by(Category.name).all()
            if Subcategory.query.filter_by(category_id=c.id).count() == 0
        ]
        if empty:
            print("still empty:", ", ".join(empty))
        else:
            print("all categories have at least one subcategory")
    return 0


if __name__ == "__main__":
    sys.exit(main())
