def slugify(name: str, max_len: int = 60) -> str:
    s = (name or "").strip().lower()
    s = re.sub(r"[^a-z0-9]+", "", s)
    if not s:
        s = re.sub(r"[^a-z0-9]+", "-", (name or "").strip().lower()).strip("-")
        s = re.sub(r"-+", "-", s)
    return (s or "item")[:max_len]


